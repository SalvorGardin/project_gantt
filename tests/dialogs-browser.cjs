// NODE_PATH=<Playwright> BROWSER_EXECUTABLE=<Chromium> node tests/dialogs-browser.cjs [URL]
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true,...(process.env.BROWSER_EXECUTABLE?{executablePath:process.env.BROWSER_EXECUTABLE}:{})});
  try {
    const page=await browser.newPage({viewport:{width:1440,height:900}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(process.argv[2]||'file://'+require('node:path').resolve(__dirname,'../index.html'));
    const active=()=>page.evaluate(()=>document.activeElement.id);
    const cycle=async id=>{
      const selectors=await page.locator('#'+id).evaluate(el=>[...el.querySelectorAll('button,input,select,textarea,a[href],[tabindex]')].filter(c=>!c.disabled&&c.tabIndex>=0&&c.getClientRects().length).map(c=>c.id));
      await page.locator('#'+selectors[0]).focus();
      await page.keyboard.press('Shift+Tab');
      assert.equal(await active(),selectors.at(-1));
      await page.keyboard.press('Tab');
      assert.equal(await active(),selectors[0]);
      await page.locator('#btn-save').evaluate(el=>el.focus());
      assert.equal(await page.evaluate(id=>document.getElementById(id).contains(document.activeElement),id),true);
    };
    await page.click('#welcome-new-btn');
    assert.equal(await active(),'new-project-name');
    await cycle('new-project-modal-overlay');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#welcome-overlay').isVisible(),true);
    await page.click('#welcome-demo-btn');
    assert.equal(await page.locator('#status-saved').textContent(),'Нет новых изменений');
    const initial=await page.evaluate(()=>gantt.serialize());
    await page.click('#btn-add-task');
    assert.equal(await active(),'edit-title');
    await cycle('modal-overlay');
    await page.click('#emoji-trigger');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#emoji-picker').isVisible(),false);
    assert.equal(await page.locator('#modal-overlay').isVisible(),true);
    assert.equal(await active(),'emoji-trigger');
    await page.keyboard.press('Escape');
    assert.equal(await active(),'btn-add-task');
    await page.waitForTimeout(150);
    assert.equal(await active(),'btn-add-task');
    assert.deepEqual(await page.evaluate(()=>gantt.serialize()),initial);
    await page.locator('.gantt_row[task_id="task_1"] .gantt_tree_content').first().dblclick();
    await page.locator('#edit-title').fill('Изменённая задача');
    await page.click('#btn-save-task');
    assert.equal(await page.locator('.toast').textContent(),'Изменения применены к плану');
    assert.equal(await page.locator('#status-unsaved').isVisible(),true);
    await page.click('#btn-new-project');
    await page.locator('#new-project-name').fill('Сохранить введённое');
    await page.click('#btn-create-project');
    assert.equal(await active(),'btn-cancel-confirm');
    await cycle('confirm-modal-overlay');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#new-project-modal-overlay').isVisible(),true);
    assert.equal(await page.locator('#new-project-name').inputValue(),'Сохранить введённое');
    assert.equal(await active(),'btn-create-project');
    await page.keyboard.press('Escape');
    assert.equal(await active(),'btn-new-project');
    // Dispatch on the link DOM node; overlapping bars make coordinate clicks ambiguous.
    await page.locator('.gantt_task_link .gantt_line_wrapper').first().dispatchEvent('dblclick');
    assert.equal(await active(),'link-type');
    await cycle('link-modal-overlay');
    const linkCount=await page.evaluate(()=>gantt.getLinks().length);
    await page.click('#btn-delete-link');
    assert.equal(await active(),'btn-cancel-confirm');
    await page.keyboard.press('Escape');
    assert.equal(await active(),'btn-delete-link');
    assert.equal(await page.evaluate(()=>gantt.getLinks().length),linkCount);
    await page.keyboard.press('Escape');
    const input={schema_version:1,project:{id:'new',name:'Импорт'},items:[],links:[]};
    await page.locator('#file-input').setInputFiles({name:'new.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(input))});
    await page.waitForSelector('#import-modal-overlay:not(.hidden)');
    assert.equal(await active(),'btn-cancel-import');
    await cycle('import-modal-overlay');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#import-modal-overlay').isVisible(),false);
    assert.notEqual(await page.locator('#project-name').inputValue(),'Импорт');
    // A failed download keeps dirty; a successful start reports only what is known.
    await page.evaluate(()=>{window.anchorClick=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){throw new Error('test download failure');};});
    await page.click('#btn-save');
    assert.match(await page.locator('.toast').textContent(),/Не удалось начать скачивание JSON/);
    assert.equal(await page.locator('#status-unsaved').isVisible(),true);
    await page.evaluate(()=>{HTMLAnchorElement.prototype.click=window.anchorClick;});
    const pending=page.waitForEvent('download');
    await page.click('#btn-save');
    const download=await pending;
    assert.ok(download.suggestedFilename().endsWith('_gantt.json'));
    assert.match(await page.locator('.toast').textContent(),/Скачивание JSON начато.*Проверьте файл/);
    assert.equal(await page.locator('#status-saved').textContent(),'Нет новых изменений');
    assert.equal(await page.locator('#status-unsaved').isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log('Five dialogs: focus, Tab/Shift+Tab, nested Escape, return, cancellation; form/download wording and error dirty passed');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
